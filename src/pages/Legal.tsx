// 内容は現在の実装の事実だけを書く。運営者名・問い合わせ先など未定のものは【未定：…】のまま表示する。
// 法的な確認はまだ受けていないため、版が "-draft" の間は「公開前の案」と明示する。

function DraftNotice({ version }: { version: string }) {
  if (!isDraftVersion(version)) return null;
  return (
    <div className="alert warn" role="note">
      <Icon name="alert" />
      <div>これは公開前の案です。【未定：…】の部分は運営者が決めて記入します。法律の専門家による確認はまだ受けていません。</div>
    </div>
  );
}

